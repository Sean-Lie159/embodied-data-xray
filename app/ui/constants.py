"""UI 层常量（仅 UI 关注的表现参数；业务阈值仍在 app/config/）。

为什么需要集中（docs/UI工程质量与配置化设计.md 2.1）：此前魔法数字散落在
``streamlit_app.py`` 与各 panel 中，后续改动（流式 / 标签页 / 重试）都要复用
这些值；集中后改一处即全局生效，且便于在文档中说明每个值的依据。

**跨层视觉常量**（配色等）不在此处，而在 ``app/visual_theme.py``——
工具层（plot_chart）也要用配色，放此处会造成"工具层依赖 UI 层"的依赖错觉
（见 docs/UI视觉优化设计.md 5.2）。本模块只放**纯 UI 布局/交互**参数。
"""

from __future__ import annotations

# 供 UI 层引用跨层视觉常量（再导出，避免各处 import 两个模块）。
from app.visual_theme import BRAND_PRIMARY, CHART_COLORS  # noqa: F401

# 左右栏滚动容器高度（px）。
# 依据：常见笔记本视口高度约 800~900px，减去标题栏/标签条/输入框后留给
# 内容区约 600px；过大会导致页面级滚动与容器滚动叠加成双重滚动条。
SCROLL_HEIGHT = 600

# 输入框钉底时为页面底部预留的高度（px）。
# 依据：st.chat_input 钉底后约 90~110px（含内边距与安全间距），取 130 留余量，
# 避免最后一条消息被遮挡。若输入框高度显著变化需重新测量并更新此值。
CHAT_INPUT_RESERVE_PX = 130

# 会话标签名最大显示长度（字符）；超出以 … 结尾。
# 依据：标签条需并排显示多个会话，超过约 18 字符会挤压其它标签。
SESSION_LABEL_MAX_CHARS = 18

# 左右栏宽度比（左：对话，右：展示区）。
COLUMN_RATIO = (1, 1.2)

# 流式输出时正文末尾的光标字符（视觉提示"还在生成中"，收尾时去掉）。
STREAM_CURSOR = "▌"

# 思考摘要框的高度（px）：固定高度使长摘要内部滚动、不挤占正文空间。
# 依据：约 8~10 行小字（小字行高较正文小），既能读到上下文又不喧宾夺主。
REASONING_BOX_HEIGHT = 200

# 思考摘要框标题（措辞用"摘要"而非"思考链"——网关回传的是模型生成的
# reasoning summary，非原始 chain-of-thought，见 docs/思考过程展示与流式过程持久化设计.md 2.1）。
REASONING_BOX_TITLE = "思考摘要"

# ---- 流式渲染节流与规模上限（2026-09-22 事故后新增）----------------------
#
# 事故：单轮提问含 4 项分析 → 思考链极长 → 后台产出 8501 个事件，而 UI 对
# **每个** reasoning 增量都执行"新建容器 + 全量重渲染"，形成平方级开销 →
# 脚本跑 196 秒后被 Streamlit 执行控制中断（StopException）→ 整轮内容丢失。
# 详见 docs/流式渲染节流与中断恢复设计.md。
#
# 节流间隔（秒）：距上次渲染超过此间隔才重渲染一次。
# 依据：0.4 秒约为人眼可感知"实时"的下限（低于此值用户察觉不到差异），
# 又能把渲染次数从"每 token 一次"降到"每秒约 2.5 次"。
PROCESS_RENDER_INTERVAL_S = 0.4

# 节流字符阈值：累积新增字符超过此值立即渲染（与时间阈值取"或"）。
# 依据：思考输出慢时避免"0.4 秒才有一次更新"的迟滞感；120 字符约 2~3 行。
PROCESS_RENDER_MIN_CHARS = 120

# 单次渲染的过程块数上限（仅流式实时渲染时生效，历史轮次不截断）。
# 依据：思考摘要框固定高度 200px 约可显示 8~10 条小字块；保留更多只是浪费
# 渲染成本（超出部分用户需滚动才可见，实时场景无意义）。
PROCESS_RENDER_MAX_BLOCKS = 40
